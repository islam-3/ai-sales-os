-- What customers asked that the business has no answer for.
--
-- This replaces asking the business our own questions. That card was
-- built, used by an owner, and failed for reasons no test would have
-- caught: it asked twelve questions of our devising while the warranty,
-- the brands and the durations already sat in the list below it. The
-- owner was being asked to redo work they had done.
--
-- What goes in this table is not our idea of what a business should
-- write. It is a question a real customer typed, which a judge then
-- confirmed nothing in the knowledge base answers. The owner is told
-- what they are losing business on, not what we think they forgot.
--
-- ── One row per ASK, not per question ───────────────────────────────
-- Five customers asking about instalments are five rows. The dashboard
-- groups them, by embedding over the short version, and the count is
-- what makes a row worth an owner's attention: one person asking about
-- parking is noise, nine asking about price is a missing page.
--
-- Grouping is NOT done here in SQL. It is a pure function over the rows
-- (lib/unanswered-questions.ts) so the rule can be tested without a
-- database, which matters because the dismissal rule below has a
-- condition that is easy to get subtly wrong.

create table if not exists public.unanswered_questions (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants (id) on delete cascade,

  -- Which conversation this came from, so the dashboard can link to it.
  -- Not a foreign key: conversations has no unique key on session_id,
  -- and a captured question should survive a transcript being cleared.
  session_id text not null,
  asked_at timestamptz not null default now(),

  -- ── The two versions, and why there are two ───────────────────────
  --
  -- question_raw is the customer's own words, in their own language,
  -- exactly as typed. It can contain anything they chose to type,
  -- including their name or their medical history.
  --
  -- question_short is a model-written version in the TEAM's language,
  -- stripped of personal detail: "does the price include the hotel?"
  -- rather than "my husband Ahmed and I fly in on the 3rd, is the
  -- hotel in the price?". It is the only one the dashboard shows and
  -- the only one that gets embedded, so no grouping decision and no
  -- rendered row ever depends on a personal detail.
  --
  -- Storing the raw version adds no exposure the owner does not
  -- already have: the same text sits in public.conversations, and the
  -- dashboard links there deliberately. It is here so a wrong short
  -- version can be traced to what was actually asked.
  question_raw text not null,
  question_short text not null,

  -- The SCRIPT the customer typed in: arabic, cyrillic, cjk, latin...
  --
  -- A script, not a language, because a script is what can be known for
  -- free and for certain from the text itself. Naming the language needs
  -- a model, and that model can be wrong — Arabic script covers Persian
  -- and Urdu, Cyrillic covers Ukrainian. The column is called what it
  -- holds so nobody later reads it as something it is not.
  --
  -- It is here for one thing: an owner seeing that seven of the nine
  -- people asking about price wrote in Arabic knows which language to
  -- write the answer in. Never used for grouping — grouping is done on
  -- the short version, which is always in the team's one language.
  script text,

  -- The embedding of question_short, which is why a fixed similarity
  -- threshold is defensible here. Similarity magnitude is language-
  -- bound (measured at 0.55 for English against 0.17 for Arabic on the
  -- same pair, see docs/answerability-detection.txt), so grouping over
  -- raw questions in mixed languages would need a per-language bar.
  -- Shortening into one language removes that problem rather than
  -- working around it.
  embedding vector(1536),

  -- What the judge said, and which model said it. For when a captured
  -- question turns out to have been answerable all along — the note is
  -- the only record of why it was not.
  judge_note text,
  judge_model text,

  -- ── Grouping ──────────────────────────────────────────────────────
  -- The id of the first ask in this group. A new group's first row
  -- points at itself. Assigned at capture time, by comparing this
  -- row's embedding against the tenant's existing groups, so a group
  -- is stable: it cannot be re-formed differently by a later read and
  -- silently reset the dismissal rule below.
  --
  -- The id is generated by the application rather than here, so that a
  -- new group's row can be written in ONE statement with group_id set
  -- to its own id. Inserting with a placeholder and repairing it
  -- afterwards leaves a window where a crash strands a row that
  -- belongs to no group and can never be shown.
  group_id uuid not null,

  -- Whether this row IS its group's canonical first ask.
  --
  -- Derived, not stored by the caller, so it cannot disagree with
  -- group_id. It exists because capture has to read "every group's
  -- canonical row" on each new ask, and PostgREST cannot compare two
  -- columns in a filter — without this the query would fetch every ask
  -- ever captured, with its 1,536-float embedding, to throw most of
  -- them away in application code.
  is_canonical boolean generated always as (id = group_id) stored,

  -- ── Dismissal ─────────────────────────────────────────────────────
  -- Set ONLY on the row where id = group_id, because dismissal belongs
  -- to the group and the canonical row is what identifies it. The
  -- constraint below enforces that, so the rule cannot be broken by a
  -- careless update.
  --
  -- A dismissed group comes back once three more customers ask after
  -- the dismissal. "I know, and I am not writing that" is a reasonable
  -- answer the first time; it stops being reasonable at the tenth
  -- customer, and the owner should get to decide again with the new
  -- number in front of them.
  dismissed_at timestamptz,

  constraint unanswered_questions_dismissal_on_canonical
    check (dismissed_at is null or id = group_id)
);

-- The dashboard's only query: this tenant's questions, newest first.
create index if not exists unanswered_questions_tenant_time_idx
  on public.unanswered_questions (tenant_id, asked_at desc);

-- Capture reads the tenant's existing groups to decide which one a new
-- ask joins, and only ever wants the canonical rows.
create index if not exists unanswered_questions_tenant_canonical_idx
  on public.unanswered_questions (tenant_id)
  where is_canonical;

alter table public.unanswered_questions enable row level security;

-- Same shape as every other tenant-scoped table: the dashboard's
-- anon-key client, signed in as the owner, sees only its own tenant.
-- The chat route writes through the service-role client and bypasses
-- RLS, so there is no insert policy for `authenticated` — an owner has
-- no business inventing customer questions.
create policy "unanswered_questions_select_own_tenant"
  on public.unanswered_questions for select
  to authenticated
  using (
    exists (
      select 1 from public.tenants t
      where t.id = unanswered_questions.tenant_id
        and t.owner_user_id = auth.uid()
    )
  );

-- Update, for dismissing. Narrower than the others on purpose: an owner
-- dismisses a group, and that is the only field they can change.
create policy "unanswered_questions_update_own_tenant"
  on public.unanswered_questions for update
  to authenticated
  using (
    exists (
      select 1 from public.tenants t
      where t.id = unanswered_questions.tenant_id
        and t.owner_user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public.tenants t
      where t.id = unanswered_questions.tenant_id
        and t.owner_user_id = auth.uid()
    )
  );

create policy "unanswered_questions_delete_own_tenant"
  on public.unanswered_questions for delete
  to authenticated
  using (
    exists (
      select 1 from public.tenants t
      where t.id = unanswered_questions.tenant_id
        and t.owner_user_id = auth.uid()
    )
  );
